"""Export representative development demo vectors and expected predictions to C++ header.

Rules:
- Uses ONLY the development partition (group g0001).
- Held-out test groups are NEVER used.
- Exports exact float samples and expected Python outputs for parity verification.
"""
from __future__ import annotations

import json
from pathlib import Path
import numpy as np

from config import DEFAULT_CONFIG
from generate_signals import build_dataset
from baselines import FixedLowDetector, FixedHighDetector
from candidate_selector import CandidateAdaptiveSelector


def export_demo_vectors(out_header: Path = Path("esp32_demo/src/demo_vectors.h"),
                        out_json: Path = Path("esp32_demo/demo_vectors_metadata.json")):
    out_header.parent.mkdir(parents=True, exist_ok=True)
    out_json.parent.mkdir(parents=True, exist_ok=True)

    print("Building development dataset for demo vector export...")
    records, signals = build_dataset(groups=80, config=DEFAULT_CONFIG, dev_calibration_fraction=0.5)
    dev_records = [r for r in records if r["split"] == "development"]

    fit_sigs = [signals[r["signal_key"]] for r in dev_records if r["dev_subset"] == "fit" and r["case"] == "normal"]
    calib_sigs = [signals[r["signal_key"]] for r in dev_records if r["dev_subset"] == "calibration" and r["case"] == "normal"]
    calib_recs = [r for r in dev_records if r["dev_subset"] == "calibration" and r["case"] == "normal"]
    calib_snrs = [r["snr_db"] for r in calib_recs]

    low_det = FixedLowDetector(4000)
    low_det.fit(fit_sigs)
    low_det.calibrate(calib_sigs, target_far=0.05)

    high_det = FixedHighDetector(4000)
    high_det.fit(fit_sigs)
    high_det.calibrate(calib_sigs, target_far=0.05)

    cand_selector = CandidateAdaptiveSelector(low_det, high_det, 4000, p_normal_percentile=60.0, p_anomaly_multiplier=1.2)
    cand_selector.calibrate_selector(calib_sigs, calib_snrs)

    demo_cases = [
        ("demo_clean_normal", "g0001", "normal", 30.0, "Clean normal signal stopped cheaply at Stage 1 as confident normal"),
        ("demo_impact", "g0001", "impact", 20.0, "High-crest impact anomaly stopped cheaply at Stage 1 as confident anomaly"),
        ("demo_frequency_shift", "g0001", "frequency_shift", 20.0, "Frequency shift detected via ZCF out-of-range, escalated to FFT"),
        ("demo_added_harmonic", "g0001", "added_harmonic", 30.0, "Subtle harmonic demonstrating frozen policy trade-off (Stage 1 miss)"),
        ("demo_noisy_normal", "g0001", "normal", 0.0, "High-noise normal escalated to FFT; Fixed-High avoids false alarm"),
    ]

    vector_metadata = []
    vector_code_blocks = []

    for name, gid, case, snr, desc in demo_cases:
        key = (gid, case, snr)
        x = signals[key]
        res = cand_selector.predict(x)

        rec = next(r for r in dev_records if r["signal_key"] == key)

        meta = {
            "name": name,
            "source_group_id": gid,
            "split": rec["split"],
            "dev_subset": rec["dev_subset"],
            "case": case,
            "snr_db": snr,
            "description": desc,
            "target_frequency_hz": rec["target_frequency_hz"],
            "python_expected": {
                "low_stage_score": float(res.low_stage_score),
                "frequency_estimate_hz": float(res.frequency_estimate_hz) if res.frequency_estimate_hz else 0.0,
                "stage_reached": res.stage_reached,
                "fft_used": bool(res.fft_used),
                "escalation_reason": res.escalation_reason,
                "predicted_label": int(res.predicted_label),
                "op_count_proxy": int(res.op_count_proxy),
            }
        }
        vector_metadata.append(meta)

        # Format C++ float array
        samples_str = ",\n    ".join(
            ", ".join(f"{val:.8f}f" for val in x[i:i+8])
            for i in range(0, len(x), 8)
        )

        c_block = f"""// {name}: {case} @ {snr:.0f}dB (Group: {gid}, {desc})
static const float {name}_samples[1024] = {{
    {samples_str}
}};
"""
        vector_code_blocks.append(c_block)

    # Build Header File
    header_content = [
        "// Auto-generated by python/export_demo_vectors.py - DO NOT EDIT MANUALLY",
        "// Deterministic development vectors for Wokwi ESP32 Adaptive Anomaly Monitoring Demo",
        "#ifndef DEMO_VECTORS_H",
        "#define DEMO_VECTORS_H",
        "",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        "",
        "struct DemoVector {",
        "    const char* name;",
        "    const char* signal_case;",
        "    float snr_db;",
        "    const char* description;",
        "    const float* samples;",
        "    float expected_low_score;",
        "    float expected_freq_hz;",
        "    const char* expected_stage;",
        "    bool expected_fft_used;",
        "    const char* expected_reason;",
        "    int expected_predicted_label;",
        "    int expected_op_count_proxy;",
        "};",
        "",
        "\n".join(vector_code_blocks),
        "",
        "static const DemoVector DEMO_VECTORS[5] = {",
    ]

    for m in vector_metadata:
        exp = m["python_expected"]
        entry = (
            f"    {{\"{m['name']}\", \"{m['case']}\", {m['snr_db']:.1f}f, \"{m['description']}\", "
            f"{m['name']}_samples, {exp['low_stage_score']:.6f}f, {exp['frequency_estimate_hz']:.4f}f, "
            f"\"{exp['stage_reached']}\", {'true' if exp['fft_used'] else 'false'}, \"{exp['escalation_reason']}\", "
            f"{exp['predicted_label']}, {exp['op_count_proxy']}}},"
        )
        header_content.append(entry)

    header_content.extend([
        "};",
        "",
        "static const int NUM_DEMO_VECTORS = 5;",
        "",
        "#endif // DEMO_VECTORS_H",
        ""
    ])

    with out_header.open("w", encoding="utf-8") as f:
        f.write("\n".join(header_content))

    with out_json.open("w", encoding="utf-8") as f:
        json.dump({
            "generator_source": "python/export_demo_vectors.py",
            "seed": DEFAULT_CONFIG.seed,
            "vectors": vector_metadata,
        }, f, indent=2)

    print(f"Exported {len(vector_metadata)} vectors to {out_header} and {out_json}")


if __name__ == "__main__":
    export_demo_vectors()
